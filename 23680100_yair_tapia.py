import duckdb
import pandas as pd
import numpy as np
import statsmodels.api as sm
import matplotlib.pyplot as plt
import seaborn as sns
from scipy import stats
from sklearn.metrics import mean_squared_error, r2_score

# 1. Configurar semilla en numpy para simulación determinista (0.42 o 42)
np.random.seed(42)

# 2. Generar datos simulados (100 registros) con distribución normal
n = 100
temperatura_max = np.random.normal(25, 5, n)
humedad_max = np.random.normal(60, 10, n)
personas_familia = np.random.normal(4, 1, n)
consumo_bidon_pc = np.random.normal(2, 0.5, n)

# 3. Aplicar la ecuación del modelo para calcular el CPC
error = np.random.normal(0, 2, n)
cpc_consumo = 54.49 + (2.40 * temperatura_max) - (0.79 * humedad_max) - (1.18 * personas_familia) + (14.88 * consumo_bidon_pc) + error

# 4. Crear un DataFrame temporal
df_simulado = pd.DataFrame({
    'temperatura_max': temperatura_max,
    'humedad_max': humedad_max,
    'personas_familia': personas_familia,
    'consumo_bidon_pc': consumo_bidon_pc,
    'cpc_consumo': cpc_consumo
})

# 5. Conexión a DuckDB en memoria y gestión de la tabla relacional
con = duckdb.connect(database=':memory:')
con.register('datos_agua_temp', df_simulado)
con.execute("CREATE TABLE datos_agua AS SELECT * FROM datos_agua_temp")

# 6. Extraer a un DataFrame final y mostrar los 5 primeros registros
df_agua = con.execute("SELECT * FROM datos_agua").df()
print("--- PASO 1: PRIMEROS 5 REGISTROS OBTENIDOS DE DUCKDB ---")
print(df_agua.head())

print("--- PASO 2: MATRIZ DE CORRELACIÓN DE PEARSON (r) ---")
matriz_correlacion = df_agua.corr()
print(matriz_correlacion)

print("\nCorrelación lineal de cada variable con la respuesta 'cpc_consumo':")
print(matriz_correlacion['cpc_consumo'].drop('cpc_consumo'))

print("\n--- PASO 3: RESUMEN DEL MODELO OLS (statsmodels) ---")
# Definir variables independientes (X) y dependiente (Y)
X_cols = ['temperatura_max', 'humedad_max', 'personas_familia', 'consumo_bidon_pc']
X = df_agua[X_cols]
Y = df_agua['cpc_consumo']

# Agregar constante para el intercepto (b0)
X = sm.add_constant(X)

# Ajustar el modelo por Mínimos Cuadrados Ordinarios (OLS)
modelo = sm.OLS(Y, X).fit()

# Mostrar la tabla de resultados
print(modelo.summary())

# Calcular predicciones y residuos
y_pred = modelo.predict(X)
residuos = modelo.resid

print("--- DIAGNÓSTICO DE RESIDUOS Y SUPUESTOS ---")
stat, p_value = stats.shapiro(residuos)
print(f"1. Prueba de Normalidad (Shapiro-Wilk): Estadístico = {stat:.4f}, valor p = {p_value:.4f}")
if p_value > 0.05:
    print("   -> CONCLUSIÓN: Los residuos cumplen con el supuesto de NORMALIDAD (p > 0.05).")

from statsmodels.stats.stattools import durbin_watson
dw = durbin_watson(residuos)
print(f"2. Estadístico Durbin-Watson (Independencia): {dw:.4f}")

print("\n--- PASO 5: MÉTRICAS DE RENDIMIENTO DEL MODELO (scikit-learn) ---")
r2 = r2_score(Y, y_pred)
rmse = np.sqrt(mean_squared_error(Y, y_pred))
print(f"Coeficiente de Determinación (R^2):\t{r2*100:.3f}%")
print(f"Error Cuadrático Medio Raíz (RMSE):\t{rmse:.4f} lt/hab-día")

# Estilo visual para los reportes de laboratorio
sns.set_theme(style="whitegrid")
fig, axes = plt.subplots(2, 3, figsize=(18, 10))
fig.suptitle('Panel de Diagnóstico Visual: Regresión Lineal Múltiple (Subtema 4.2)', fontsize=16, fontweight='bold')

# 1. Mapa de Calor de Correlación
sns.heatmap(matriz_correlacion, annot=True, fmt=".2f", cmap="coolwarm", cbar=True, ax=axes[0, 0])
axes[0, 0].set_title('1. Matriz de Correlación de Pearson (r)')

# 2. Scatter Plot: Humedad vs Consumo
sns.regplot(data=df_agua, x='humedad_max', y='cpc_consumo', color='b', ax=axes[0, 1],
            line_kws={'color': 'red', 'linewidth': 2})
axes[0, 1].set_title('2. Tendencia: Humedad Máx vs Consumo')
axes[0, 1].set_xlabel('Humedad Máxima (%)')
axes[0, 1].set_ylabel('CPC Consumo (lt/hab-día)')

# 3. Valores Reales vs Predichos
axes[0, 2].scatter(y_pred, Y, alpha=0.7, color='teal')
axes[0, 2].plot([Y.min(), Y.max()], [Y.min(), Y.max()], 'r--', lw=2)
axes[0, 2].set_title('3. Val. Reales vs Predichos')
axes[0, 2].set_xlabel('CPC Predicho (ŷ)')
axes[0, 2].set_ylabel('CPC Real (y)')

# 4. Residuos vs Valores Ajustados (Homocedasticidad)
axes[1, 0].scatter(y_pred, residuos, color='purple', alpha=0.6)
axes[1, 0].axhline(y=0, color='r', linestyle='--', lw=2)
axes[1, 0].set_title('4. Residuos vs Ajustados (Homocedasticidad)')
axes[1, 0].set_xlabel('Valores Predichos (ŷ)')
axes[1, 0].set_ylabel('Residuos (e = y - ŷ)')

# 5. Gráfico Q-Q Normal (Normalidad de Errores)
sm.qqplot(residuos, line='45', fit=True, ax=axes[1, 1])
axes[1, 1].set_title('5. Gráfico Q-Q Normal (Residuos)')

# Ocultar la celda sobrante
axes[1, 2].axis('off')

plt.tight_layout()
plt.show()

